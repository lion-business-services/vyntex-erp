// Builds supabase/migrations/0076_partner_catalog_seed.sql from docs/partners/catalog-import.json (the Phase A audit).
//
//   node scripts/partners/build-catalog-seed.mjs          writes the migration
//   node scripts/partners/build-catalog-seed.mjs --check  fails when the migration is not what the JSON gives
//
// Rules (docs/partners/CATALOG-MAPPING.md):
//   * ERP software (categories erp_build, erp_addons) is left out: its prices come only from config/vyntex-build-pricing.json.
//   * Every item is imported as an UNPUBLISHED draft (version 1). Items with a conflict or a missing figure are
//     "needs_approval" and quote only. A partner_admin publishes (one by one, or partner_admin_catalog_publish_ready()).
//   * Every policy is imported as a draft (approved in the source) or needs_approval version 1. None is approved here.
//   * Amounts stay integer cents and rates basis points, exactly as in the JSON. Provenance is kept on every row.
//   * Client-facing text: the em dashes of the source are written as a colon (house style for client documents);
//     the original wording is otherwise unchanged.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = JSON.parse(readFileSync(join(root, 'docs/partners/catalog-import.json'), 'utf8'));
const out = join(root, 'supabase/migrations/0076_partner_catalog_seed.sql');

const ERP = new Set(['erp_build', 'erp_addons']);
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v ?? {}))}::jsonb`;
const dash = (v) => {
  if (typeof v === 'string') return v.replace(/\s*—\s*/g, ': ');
  if (Array.isArray(v)) return v.map(dash);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, dash(x)]));
  return v;
};
const KIND = { package: 'package', service: 'service', add_on: 'add_on', hourly_rate: 'hourly_rate' };
const PERIOD = (p) => {
  if (p.kind === 'hourly') return 'hour';
  if (p.kind === 'per_unit') return 'unit';
  if (p.billing_period === 'month' || p.billing_period === 'year') return p.billing_period;
  if (p.kind === 'recurring') return 'month';
  return 'one_time';
};
const priceLabel = (p) => {
  if (p.kind === 'surcharge' && p.rate_bps) return { en: `+${p.rate_bps / 100}% of the ${p.applies_to || 'setup'}`, es: `+${p.rate_bps / 100}% de la ${p.applies_to === 'setup' || !p.applies_to ? 'instalación' : p.applies_to}` };
  return {};
};

export function buildSeed() {
  const L = [];
  L.push('-- 0076 VYNTEX Partner Portal, part 7: the reference import of the Master Command commercial catalog.');
  L.push('-- GENERATED by scripts/partners/build-catalog-seed.mjs from docs/partners/catalog-import.json. Do not edit by hand.');
  L.push('-- Nothing here is published or approved: a partner_admin reviews and publishes in the portal (docs/partners/README.md).');
  L.push(`-- Source: ${src.sources.master_command_repo}; generated ${src.generated_at}; import schema ${src.schema}.`);
  L.push('');
  const cats = src.categories.filter((c) => !ERP.has(c.id));
  cats.forEach((c, i) => {
    L.push(`insert into partner.catalog_categories (id, name, sort, provenance) values (${q(c.id)}, ${j(c.name)}, ${(i + 1) * 10}, ${j(c.provenance)}) on conflict (id) do nothing;`);
  });
  L.push('');
  const items = src.services.filter((s) => !ERP.has(s.category) && KIND[s.kind]);
  items.forEach((s, i) => {
    const needs = s.status !== 'approved_source';
    const prov = { text: s.text_provenance ?? null, status: s.status, publication: s.publication, notes: s.notes ?? [], bilingual: s.bilingual ?? null, import: src.schema };
    L.push(`insert into partner.catalog_items (id, category_id, kind, sort) values (${q(s.id)}, ${q(s.category)}, ${q(KIND[s.kind])}, ${(i + 1) * 10}) on conflict (id) do nothing;`);
    L.push(`insert into partner.catalog_versions (item_id, version, status, client_facing, popular, quote_only, name, tagline, best_for, includes, excludes, lead_time, provenance)`);
    L.push(`  select ${q(s.id)}, 1, ${q(needs ? 'needs_approval' : 'draft')}, ${s.client_facing ? 'true' : 'false'}, ${s.popular ? 'true' : 'false'}, ${needs ? 'true' : 'false'},`);
    L.push(`    ${j(dash(s.name))}, ${j(dash(s.tagline ?? {}))}, ${j(dash(s.best_for ?? {}))}, ${j(dash(s.includes ?? {}))}, ${j(dash(s.excludes ?? {}))}, ${j(dash(s.lead_time ?? {}))}, ${j(prov)}`);
    L.push(`  where not exists (select 1 from partner.catalog_versions where item_id = ${q(s.id)});`);
    (s.prices || []).forEach((p, n) => {
      const kind = ['setup', 'recurring', 'one_time', 'deposit', 'hourly', 'surcharge', 'per_unit', 'quote'].includes(p.kind) ? p.kind : 'quote';
      const pprov = { ...(p.provenance || {}), ...(p.rule ? { rule: p.rule } : {}), ...(p.derived ? { derived: true } : {}), ...(p.exact_half_cents !== undefined ? { exact_half_cents: p.exact_half_cents } : {}), ...(p.note ? { note: p.note } : {}) };
      L.push(`insert into partner.catalog_prices (version_id, kind, amount_cents, period, optional, minimum_term_months, status, label, provenance, sort)`);
      L.push(`  select v.id, ${q(kind)}, ${p.amount_cents ?? 'null'}, ${q(PERIOD(p))}, ${p.optional ? 'true' : 'false'}, ${p.minimum_term_months ?? 'null'}, ${q(p.status === 'approved_source' || p.status === 'needs_approval' || p.status === 'informational_estimate' ? p.status : 'needs_approval')}, ${j(priceLabel(p))}, ${j(pprov)}, ${n + 1}`);
      L.push(`    from partner.catalog_versions v where v.item_id = ${q(s.id)} and v.version = 1`);
      L.push(`     and not exists (select 1 from partner.catalog_prices x where x.version_id = v.id and x.sort = ${n + 1});`);
    });
  });
  L.push('');

  // resources: the client-facing terms (proposals show the published ones), the partner selling rules, third-party usage
  const TERMS = {
    deposit: ['terms', { en: 'Deposit and balance', es: 'Anticipo y saldo' }],
    setup_split: ['terms', { en: 'Paying the setup in parts', es: 'Pago de la instalación en partes' }],
    minimum_term: ['terms', { en: 'Minimum term', es: 'Plazo mínimo' }],
    annual_prepay: ['terms', { en: 'Paying a year in advance', es: 'Pago anual por adelantado' }],
    early_cancel: ['terms', { en: 'Cancelling early', es: 'Cancelación anticipada' }],
    proposal_validity: ['terms', { en: 'How long a proposal is valid', es: 'Vigencia de la propuesta' }],
    monthly_floor: ['guide', { en: 'Monthly price floor (partner rule)', es: 'Precio mensual mínimo (regla para socios)' }],
  };
  for (const t of src.commercial_terms) {
    if (!TERMS[t.id]) continue;
    const [kind, title] = TERMS[t.id];
    const prov = { ...(t.provenance || {}), status: t.status, corroborated_by: t.corroborated_by ?? [], translation_needed: 'es' };
    L.push(`insert into partner.resources (slug, version, kind, status, title, body, provenance) select ${q('term-' + t.id.replace(/_/g, '-'))}, 1, ${q(kind)}, ${q(t.status === 'approved_source' ? 'draft' : 'needs_approval')}, ${j(title)}, ${j({ en: dash(t.rule) })}, ${j(prov)}`);
    L.push(`  where not exists (select 1 from partner.resources where slug = ${q('term-' + t.id.replace(/_/g, '-'))});`);
  }
  const usage = src.pass_through_usage;
  const usageBody = {
    en: ['Billed at cost to the client; never commissionable. Estimates only, not VYNTEX prices:', ...usage.map((u) => `${u.name.en}: ${u.estimate_display.replace(/–/g, ' to ')}`)].join('\n'),
    es: ['Se cobran al cliente al costo y nunca generan comisión. Son estimados, no precios de VYNTEX:', ...usage.map((u) => `${u.name.es}: ${u.estimate_display.replace(/–/g, ' a ').replace(/\/mo\b/g, '/mes').replace(/\beach\b/g, 'c/u').replace(/\bonce\b/g, 'único')}`)].join('\n'),
  };
  L.push(`insert into partner.resources (slug, version, kind, status, title, body, provenance) select 'third-party-usage', 1, 'disclosure', 'draft', ${j({ en: 'Third-party usage costs', es: 'Costos de uso de terceros' })}, ${j(usageBody)}, ${j({ status: 'approved_source', items: usage.map((u) => u.provenance) })}`);
  L.push(`  where not exists (select 1 from partner.resources where slug = 'third-party-usage');`);
  L.push('');

  // policies
  const name = (p) => {
    const usd = (c) => `$${(c / 100).toFixed(0)}`;
    switch (p.model) {
      case 'referral_flat_fee': return p.amount_cents ? { en: `Referral fee ${usd(p.amount_cents)}`, es: `Comisión por referido de ${usd(p.amount_cents)}` } : { en: `Referral fee (${p.id.replace('referral-', '')})`, es: `Comisión por referido (${p.id.replace('referral-', '')})` };
      case 'revenue_share_setup': return { en: `Revenue share: ${p.rate_bps / 100}% of setup`, es: `Participación: ${p.rate_bps / 100}% de la instalación` };
      case 'revenue_share_recurring': return { en: `Revenue share: ${p.rate_bps / 100}% of each month collected`, es: `Participación: ${p.rate_bps / 100}% de cada mes cobrado` };
      case 'revenue_share_one_time': return { en: `Revenue share: ${p.rate_bps / 100}% of one-time work`, es: `Participación: ${p.rate_bps / 100}% de trabajos únicos` };
      default: return { en: p.id.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase()), es: p.id.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase()) };
    }
  };
  const CALC = new Set(['referral_flat_fee', 'revenue_share_setup', 'revenue_share_recurring', 'revenue_share_one_time']);
  const LANES = new Set(['referral', 'revshare', 'authorized_reseller', 'website_reseller', 'all']);
  const MODELS = new Set(['referral_flat_fee', 'revenue_share_setup', 'revenue_share_recurring', 'revenue_share_one_time', 'exclusion', 'rule', 'non_cash_alternative', 'reseller_commission', 'wholesale_margin', 'undefined']);
  for (const p of src.commission_policies) {
    const terms = Object.fromEntries(Object.entries(p).filter(([k]) => !['provenance', 'corroborated_by', 'conflicts'].includes(k)));
    const applies = CALC.has(p.model) ? (p.applies_to || []).map((a) => a.replace(/\s*\(.*\)$/, '')) : [];
    const trigger = typeof p.trigger === 'string' ? p.trigger : '';
    const payoutDays = /within 15 days/.test(trigger) || /same as referral-flat-150/.test(trigger) ? 15 : null;
    const prov = { ...(p.provenance || {}), corroborated_by: p.corroborated_by ?? [], source_status: p.status };
    L.push(`insert into partner.policies (id, name, provenance, conflicts) values (${q(p.id)}, ${j(name(p))}, ${j(prov)}, ${j(p.conflicts ?? [])}) on conflict (id) do nothing;`);
    L.push(`insert into partner.policy_versions (policy_id, version, status, model, lane, amount_cents, rate_bps, applies_to, min_order_cents, clawback_days, payout_days, trigger_rule, note, terms)`);
    L.push(`  select ${q(p.id)}, 1, ${q(p.status === 'approved_source' ? 'draft' : 'needs_approval')}, ${q(MODELS.has(p.model) ? p.model : 'undefined')}, ${p.lane && LANES.has(p.lane) ? q(p.lane) : 'null'},`);
    L.push(`    ${p.amount_cents ?? 'null'}, ${p.rate_bps ?? 'null'}, ${applies.length ? `array[${applies.map(q).join(', ')}]::text[]` : `'{}'::text[]`}, ${p.min_order_cents ?? 'null'}, ${p.clawback?.window_days ?? 'null'}, ${payoutDays ?? 'null'},`);
    L.push(`    ${q(trigger.slice(0, 1000))}, ${q(String(p.note ?? '').slice(0, 2000))}, ${j(terms)}`);
    L.push(`  where not exists (select 1 from partner.policy_versions where policy_id = ${q(p.id)});`);
  }
  L.push('');
  L.push('select partner.lockdown_check();');
  L.push('select app.lockdown_check();');
  return L.join('\n') + '\n';
}

const sql = buildSeed();
if (process.argv.includes('--check')) {
  const have = readFileSync(out, 'utf8');
  if (have !== sql) { console.error('0076_partner_catalog_seed.sql is out of date: run node scripts/partners/build-catalog-seed.mjs'); process.exit(1); }
  console.log('partner catalog seed matches docs/partners/catalog-import.json');
} else {
  writeFileSync(out, sql);
  console.log('wrote', out);
}
